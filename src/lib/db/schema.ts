/**
 * Drizzle schema. Mirrors the domain types in `src/types/`.
 *
 * Keep this file free of `astro:*` imports: drizzle-kit and the seed script
 * load it outside Astro.
 */
import { sql } from 'drizzle-orm';
import { boolean, check, date, doublePrecision, index, integer, pgEnum, pgTable, text, timestamp, uniqueIndex } from 'drizzle-orm/pg-core';
import { CONTACT_REQUEST_STATUSES, ROOM_STATUSES, WATER_UNITS } from '../../types';
import { user } from './auth-schema';

export * from './auth-schema';

export const roomStatus = pgEnum('room_status', ROOM_STATUSES);
export const contactRequestStatus = pgEnum('contact_request_status', CONTACT_REQUEST_STATUSES);
export const waterUnit = pgEnum('water_unit', WATER_UNITS);

/**
 * One row per landlord. `id` equals the Better Auth `user.id` (1-to-1), so
 * this table holds only the landlord profile, not credentials. The row is
 * created by the Better Auth user hook (`src/lib/auth/create-auth.ts`).
 * `email` mirrors `user.email`, which is the source of truth.
 */
export const landlords = pgTable('landlords', {
  id: text('id')
    .primaryKey()
    .references(() => user.id, { onDelete: 'cascade' }),
  name: text('name').notNull(),
  phone: text('phone').notNull(),
  zalo: text('zalo'),
  email: text('email').notNull().unique(),
});

export const rooms = pgTable(
  'rooms',
  {
    id: text('id').primaryKey(),
    landlordId: text('landlord_id')
      .notNull()
      .references(() => landlords.id, { onDelete: 'cascade' }),
    title: text('title').notNull(),
    description: text('description').notNull(),
    /** Monthly rent in VND. */
    price: integer('price').notNull(),
    /** Deposit in VND. */
    deposit: integer('deposit').notNull(),
    /** Square meters. */
    area: integer('area').notNull(),
    address: text('address').notNull(),
    /** Official ward/commune name (`src/lib/locations.ts`). */
    ward: text('ward').notNull(),
    /**
     * `slugify(ward)` and `slugify(neighborhood)`, stored so listings can filter
     * by the `khu-vuc` URL slug in SQL. DB-only: not part of the `Room` type.
     * Always write them with `toRoomRow`.
     */
    wardSlug: text('ward_slug').notNull(),
    /** Former ward name ("Khu vực quen gọi"), optional. */
    neighborhood: text('neighborhood'),
    neighborhoodSlug: text('neighborhood_slug'),
    province: text('province').notNull(),
    /** WGS84; both set or both null (see `toRoom`). */
    lat: doublePrecision('lat'),
    lng: doublePrecision('lng'),
    /**
     * Utilities (`Room.utilities`). Each: null = "Thỏa thuận", 0 = free / included.
     * Electricity is either the state tariff (`electricity_state_rate`) or a
     * price per kWh; water is a price per m³ or per person.
     */
    electricityStateRate: boolean('electricity_state_rate').notNull().default(false),
    electricityPrice: integer('electricity_price'),
    waterPrice: integer('water_price'),
    waterUnit: waterUnit('water_unit'),
    wifiPrice: integer('wifi_price'),
    serviceFee: integer('service_fee'),
    amenities: text('amenities').array().notNull().default([]),
    // New rooms have no photos yet, so they start hidden (also set explicitly in createRoom).
    status: roomStatus('status').notNull().default('hidden'),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    /** First time the room became `available`; set once by the landlord queries (`Room.publishedAt`). */
    publishedAt: timestamp('published_at', { withTimezone: true }),
    updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    // Listings: newest first by publish date.
    index('rooms_status_published_at_idx').on(table.status, table.publishedAt),
    index('rooms_status_ward_slug_idx').on(table.status, table.wardSlug),
    index('rooms_status_neighborhood_slug_idx').on(table.status, table.neighborhoodSlug),
    index('rooms_landlord_id_idx').on(table.landlordId),
    // Map viewport queries: status, then a latitude range.
    index('rooms_status_lat_lng_idx').on(table.status, table.lat, table.lng),
    check('rooms_amounts_valid', sql`${table.price} >= 0 and ${table.deposit} >= 0 and ${table.area} > 0`),
    check('rooms_location_pair', sql`(${table.lat} is null) = (${table.lng} is null)`),
    check('rooms_water_pair', sql`(${table.waterPrice} is null) = (${table.waterUnit} is null)`),
    check('rooms_electricity_mode', sql`not (${table.electricityStateRate} and ${table.electricityPrice} is not null)`),
    check(
      'rooms_costs_non_negative',
      sql`coalesce(${table.electricityPrice}, 0) >= 0 and coalesce(${table.waterPrice}, 0) >= 0 and coalesce(${table.wifiPrice}, 0) >= 0 and coalesce(${table.serviceFee}, 0) >= 0`,
    ),
  ],
);

/**
 * Room photos in object storage (R2). Keys are generated by the server:
 * `rooms/{roomId}/{uuid}.webp` and `rooms/{roomId}/{uuid}-thumb.webp`.
 * Deleting a row does not delete the objects: the code that deletes rows
 * also deletes the objects, and `npm run r2:orphans` finds leftovers.
 */
export const roomPhotos = pgTable(
  'room_photos',
  {
    id: text('id').primaryKey(),
    roomId: text('room_id')
      .notNull()
      .references(() => rooms.id, { onDelete: 'cascade' }),
    key: text('key').notNull(),
    thumbKey: text('thumb_key').notNull(),
    /** Pixel size of the full image. */
    width: integer('width').notNull(),
    height: integer('height').notNull(),
    sortOrder: integer('sort_order').notNull(),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    index('room_photos_room_id_sort_order_idx').on(table.roomId, table.sortOrder),
    uniqueIndex('room_photos_key_idx').on(table.key),
    uniqueIndex('room_photos_thumb_key_idx').on(table.thumbKey),
    check('room_photos_size_positive', sql`${table.width} > 0 and ${table.height} > 0`),
  ],
);

export const contactRequests = pgTable(
  'contact_requests',
  {
    id: text('id').primaryKey(),
    roomId: text('room_id')
      .notNull()
      .references(() => rooms.id, { onDelete: 'cascade' }),
    renterName: text('renter_name').notNull(),
    renterPhone: text('renter_phone').notNull(),
    message: text('message').notNull(),
    preferredViewingTime: text('preferred_viewing_time'),
    status: contactRequestStatus('status').notNull().default('new'),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    // Inbox: a landlord's requests by room, status and date; duplicate check by room + phone.
    index('contact_requests_room_id_status_created_at_idx').on(table.roomId, table.status, table.createdAt),
    index('contact_requests_room_id_phone_idx').on(table.roomId, table.renterPhone),
  ],
);

/**
 * Fixed-window counters for the chat assistant (`src/lib/rate-limit.ts`).
 * `key` is a hash of the client IP, never the IP itself.
 */
export const chatRateLimits = pgTable('chat_rate_limits', {
  key: text('key').primaryKey(),
  windowStart: timestamp('window_start', { withTimezone: true }).notNull(),
  count: integer('count').notNull(),
});

/** Same fixed-window counters for the renter contact form (`src/lib/rate-limit.ts`). */
export const contactRateLimits = pgTable('contact_rate_limits', {
  key: text('key').primaryKey(),
  windowStart: timestamp('window_start', { withTimezone: true }).notNull(),
  count: integer('count').notNull(),
});

/**
 * Same counters for presigned photo upload URLs, per landlord (`key` is a hash
 * of the landlord id). Unconfirmed uploads stay in R2 until `r2:orphans`.
 */
export const uploadRateLimits = pgTable('upload_rate_limits', {
  key: text('key').primaryKey(),
  windowStart: timestamp('window_start', { withTimezone: true }).notNull(),
  count: integer('count').notNull(),
});

/**
 * Gmail sends per calendar day in Asia/Ho_Chi_Minh (`src/lib/email-core.ts`),
 * to stay under Gmail's ~500/day limit. Only the `gmail` transport counts.
 */
export const emailSendCounts = pgTable('email_send_counts', {
  day: date('day').primaryKey(),
  count: integer('count').notNull(),
});

export type RoomRow = typeof rooms.$inferSelect;
export type NewRoomRow = typeof rooms.$inferInsert;
export type RoomPhotoRow = typeof roomPhotos.$inferSelect;
